#!/usr/bin/env node
'use strict';
/**
 * build-web-dist — deterministic static Web Preview bundle.
 *
 * Copies the renderer into web-dist/ and stamps the web build metadata. The
 * EXCLUSION list is read from package.json build.files (the same `!renderer/...`
 * entries electron-builder uses), so the web bundle can never ship a deferred
 * module the DMG excludes — one truth source, no duplicated lists.
 *
 * Output (pure static, no backend, subpath-safe — all asset paths relative):
 *   web-dist/index.html
 *   web-dist/lib/**            vendored libs (alpine/chart/tailwind)
 *   web-dist/js/**             renderer modules minus excluded ones
 *   web-dist/js/web-build-info.js   GENERATED — the single version stamping point
 *   web-dist/404.html, web-dist/.nojekyll
 *
 * Never included: main.js, preload.js, node_modules, tests, governance, docs,
 * scripts, build artifacts, DMG. A trailing self-audit enforces that and exits
 * non-zero on any violation (fail-closed, same spirit as the release gates).
 */
const fs = require('fs');
const path = require('path');
const cp = require('child_process');

const REPO = path.resolve(__dirname, '..');
const OUT = path.join(REPO, 'web-dist');
const pkg = JSON.parse(fs.readFileSync(path.join(REPO, 'package.json'), 'utf8'));

// Exclusions from the electron-builder files list — single truth source.
const excluded = (pkg.build && pkg.build.files ? pkg.build.files : [])
  .filter((e) => typeof e === 'string' && e.startsWith('!renderer/'))
  .map((e) => e.slice('!renderer/'.length));
if (excluded.length === 0) { console.error('WEB-DIST FATAL: no exclusion entries found in package.json build.files'); process.exit(2); }

function gitShort() {
  try { return cp.execSync('git rev-parse --short=9 HEAD', { cwd: REPO, encoding: 'utf8' }).trim(); }
  catch (_) { return 'unknown'; }
}

// -- clean output dir (only ours; refuses odd paths defensively)
if (!OUT.endsWith('web-dist')) { console.error('WEB-DIST FATAL: refusing to clean unexpected path ' + OUT); process.exit(2); }
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'lib'), { recursive: true });

// -- copy renderer (respecting exclusions)
const copied = [];
function copyDir(srcDir, dstDir, relPrefix) {
  for (const name of fs.readdirSync(srcDir)) {
    const rel = relPrefix ? relPrefix + '/' + name : name;
    const src = path.join(srcDir, name);
    const dst = path.join(dstDir, name);
    const st = fs.statSync(src);
    if (st.isDirectory()) { fs.mkdirSync(dst, { recursive: true }); copyDir(src, dst, rel); continue; }
    if (excluded.includes(rel)) continue;
    fs.copyFileSync(src, dst);
    copied.push(rel);
  }
}
copyDir(path.join(REPO, 'renderer'), OUT, '');

// -- stamp web build metadata (THE single stamping point; replaces the source no-op)
const buildInfo =
  '// GENERATED by scripts/build-web-dist.js — do not edit; see renderer/js/web-build-info.js for the contract.\n' +
  'window.WEB_BUILD_INFO = Object.freeze({\n' +
  `  version: ${JSON.stringify(pkg.version)},\n` +
  "  channel: 'web-preview',\n" +
  `  commit: ${JSON.stringify(gitShort())},\n` +
  `  builtAt: ${JSON.stringify(new Date().toISOString())}\n` +
  '});\n';
fs.writeFileSync(path.join(OUT, 'js', 'web-build-info.js'), buildInfo);

// -- Pages hygiene files
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
fs.writeFileSync(path.join(OUT, '404.html'),
  '<!doctype html><meta charset="utf-8"><title>Racing Setup Analyzer</title>' +
  '<p>Not found. <a href="./">Open the Racing Setup Analyzer Web Preview</a>.</p>\n');

// -- self-audit (fail-closed)
const problems = [];
const banned = ['main.js', 'preload.js', 'node_modules', 'tests', 'governance', 'docs', 'scripts', 'build', 'package.json', 'package-lock.json'];
for (const b of banned) if (fs.existsSync(path.join(OUT, b))) problems.push('banned path present: ' + b);
for (const ex of excluded) if (fs.existsSync(path.join(OUT, ex))) problems.push('excluded module leaked: ' + ex);
if (!fs.existsSync(path.join(OUT, 'index.html'))) problems.push('index.html missing');
if (!fs.existsSync(path.join(OUT, 'js', 'runtime-api.js'))) problems.push('runtime-api.js missing');
const stamped = fs.readFileSync(path.join(OUT, 'js', 'web-build-info.js'), 'utf8');
if (!stamped.includes(`version: ${JSON.stringify(pkg.version)}`)) problems.push('web-build-info version stamp mismatch');
const html = fs.readFileSync(path.join(OUT, 'index.html'), 'utf8');
if (/src="\/|href="\//.test(html)) problems.push('absolute asset path found in index.html (breaks Pages subpath)');
// no DMG or archives of any kind
function scanBig(dir) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    const st = fs.statSync(p);
    if (st.isDirectory()) { scanBig(p); continue; }
    if (/\.(dmg|zip|tar|gz|asar)$/i.test(name)) problems.push('artifact file in web-dist: ' + path.relative(OUT, p));
  }
}
scanBig(OUT);

const summary = { tool: 'build-web-dist', version: pkg.version, commit: gitShort(), files: copied.length + 3, excludedCount: excluded.length, problems, ok: problems.length === 0 };
console.log('WEB-DIST ' + JSON.stringify(summary));
process.exit(problems.length === 0 ? 0 : 1);
